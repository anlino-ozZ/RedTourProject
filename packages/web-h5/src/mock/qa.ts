/**
 * Mock 问答：按关键词命中返回答案，未命中走兜底
 * @param question 用户问题
 */
export function getAnswer(question: string): QaAnswer {
  const q = question.toLowerCase()
  for (const rule of RULES) {
    if (rule.keywords.some((k) => q.includes(k.toLowerCase()))) {
      return rule.answer
    }
  }
  return FALLBACK
}
